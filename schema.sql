-- Tailor Order Book: database schema (MySQL 5.7+ / MariaDB 10.3+)
--
-- Run once:   mysql -u root -p < sql/schema.sql
-- Then create a user for the app (see README.md) and put it in api/config.php.

CREATE DATABASE IF NOT EXISTS tailor_book
  DEFAULT CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

USE tailor_book;

-- One row per person. Repeat customers share a row (matched by name + phone).
CREATE TABLE IF NOT EXISTS customers (
  id          INT UNSIGNED NOT NULL AUTO_INCREMENT,
  name        VARCHAR(120) NOT NULL DEFAULT '',
  phone       VARCHAR(40)  NOT NULL DEFAULT '',
  email       VARCHAR(120) NOT NULL DEFAULT '',
  address     VARCHAR(300) NOT NULL DEFAULT '',
  created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_customers_name  (name),
  KEY idx_customers_phone (phone)
) ENGINE=InnoDB;

-- One row per tailoring job.
CREATE TABLE IF NOT EXISTS orders (
  id             VARCHAR(40)  NOT NULL,                 -- generated by the page, e.g. "o1k3x9ab2"
  order_no       VARCHAR(20)  NOT NULL,                 -- shop-facing number, e.g. "T-0007"
  customer_id    INT UNSIGNED NOT NULL,
  type           VARCHAR(40)  NOT NULL DEFAULT 'Other', -- Dress, Uniform, Suit / Formal, Alteration, Curtains, Bedding, Other
  item           VARCHAR(200) NOT NULL DEFAULT '',      -- what is being made, e.g. "Debut gown, ivory satin"
  received_date  DATE         NOT NULL,
  due_date       DATE         NULL,
  status         ENUM('New','Measured','Sewing','Fitting','Ready','Picked up') NOT NULL DEFAULT 'New',
  is_cancelled   TINYINT(1)   NOT NULL DEFAULT 0,       -- the "Cancelled by customer" switch
  cancelled_at   DATE         NULL,
  unit           ENUM('cm','in') NOT NULL DEFAULT 'cm', -- unit used for this order's measurements
  adjustments    TEXT         NULL,                     -- specific adjustment requests
  fee            DECIMAL(10,2) NOT NULL DEFAULT 0.00,   -- tailoring fee (labour)
  deposit        DECIMAL(10,2) NOT NULL DEFAULT 0.00,
  is_sample      TINYINT(1)   NOT NULL DEFAULT 0,       -- example rows shown with a "Sample" tag
  created_at     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_orders_order_no (order_no),
  KEY idx_orders_customer (customer_id),
  KEY idx_orders_status_due (status, due_date),
  CONSTRAINT fk_orders_customer FOREIGN KEY (customer_id) REFERENCES customers (id)
) ENGINE=InnoDB;

-- Body measurements, or window / home measurements for non-clothing jobs.
-- Free labels so each shop can use its own names. Value is text because
-- entries like "2x" (curtain fullness) are common.
CREATE TABLE IF NOT EXISTS order_measurements (
  id          INT UNSIGNED NOT NULL AUTO_INCREMENT,
  order_id    VARCHAR(40)  NOT NULL,
  sort_order  SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  label       VARCHAR(60)  NOT NULL DEFAULT '',
  value       VARCHAR(20)  NOT NULL DEFAULT '',
  PRIMARY KEY (id),
  KEY idx_measurements_order (order_id, sort_order),
  CONSTRAINT fk_measurements_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- Materials needed for the job. A cost of 0 means the customer supplies it.
CREATE TABLE IF NOT EXISTS order_materials (
  id          INT UNSIGNED NOT NULL AUTO_INCREMENT,
  order_id    VARCHAR(40)  NOT NULL,
  sort_order  SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  name        VARCHAR(120) NOT NULL DEFAULT '',
  qty         VARCHAR(30)  NOT NULL DEFAULT '',           -- "4 m", "18", "2 rolls"
  cost        DECIMAL(10,2) NOT NULL DEFAULT 0.00,
  PRIMARY KEY (id),
  KEY idx_materials_order (order_id, sort_order),
  CONSTRAINT fk_materials_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- Small key/value table for app settings (currency symbol).
CREATE TABLE IF NOT EXISTS settings (
  setting_key    VARCHAR(40)  NOT NULL,
  setting_value  VARCHAR(200) NOT NULL DEFAULT '',
  PRIMARY KEY (setting_key)
) ENGINE=InnoDB;

-- Handy read-only summary for reports: totals and balance per order.
-- Example: SELECT * FROM v_order_summary WHERE is_cancelled = 0 AND balance_due > 0;
CREATE OR REPLACE VIEW v_order_summary AS
SELECT o.id,
       o.order_no,
       c.name  AS customer,
       c.phone,
       o.type,
       o.item,
       o.status,
       o.is_cancelled,
       o.due_date,
       o.fee,
       COALESCE(m.materials_cost, 0)                 AS materials_cost,
       o.fee + COALESCE(m.materials_cost, 0)         AS total,
       o.deposit,
       o.fee + COALESCE(m.materials_cost, 0) - o.deposit AS balance_due
  FROM orders o
  JOIN customers c ON c.id = o.customer_id
  LEFT JOIN (
        SELECT order_id, SUM(cost) AS materials_cost
          FROM order_materials
         GROUP BY order_id
       ) m ON m.order_id = o.id;
